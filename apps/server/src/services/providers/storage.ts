import { createHash, randomBytes } from 'node:crypto';
import { mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, join, normalize, resolve, sep } from 'node:path';

/**
 * Where uploaded bytes live.
 *
 * An interface because step 37 may want object storage and because tests must
 * not touch a disk they share with other tests. The local implementation is
 * the only one this release ships, and it is deliberately dull: files under a
 * directory the web server does not serve.
 *
 * **Nothing here is reachable by URL.** The storage root is outside any static
 * root, and nginx has no rule that maps to it. A file is only ever delivered
 * by the download route, which performs an ownership check first. "Private
 * storage" is that property, not a filename nobody has guessed.
 */

export interface StoredObject {
  readonly key: string;
  readonly byteSize: number;
  readonly checksumSha256: string;
}

export interface StorageProvider {
  put(key: string, bytes: Buffer): Promise<StoredObject>;
  get(key: string): Promise<Buffer>;
  delete(key: string): Promise<void>;
  exists(key: string): Promise<boolean>;
}

/**
 * Generates a storage key.
 *
 * Server-side and unguessable, never derived from the customer's filename.
 * Their filename is metadata — it is stored for display and never used to
 * build a path, because `../../etc/passwd` and `.jpg.php` are both filenames.
 *
 * Sharded by the first two characters so one directory does not accumulate a
 * hundred thousand entries, which makes `ls` and every directory read slow on
 * most filesystems.
 */
export function newStorageKey(): string {
  const random = randomBytes(16).toString('hex');
  return `${random.slice(0, 2)}/${random}`;
}

export function sha256(bytes: Buffer): string {
  return createHash('sha256').update(bytes).digest('hex');
}

export class LocalFileStorage implements StorageProvider {
  constructor(private readonly root: string) {}

  /**
   * Resolves a key to a path, refusing anything that escapes the root.
   *
   * Keys are generated by `newStorageKey`, so a traversal should be
   * impossible — this is the check that makes "should be" into "is". It is
   * three lines, and the alternative is trusting that no future caller ever
   * passes a key that came from somewhere else.
   */
  private pathFor(key: string): string {
    const base = resolve(this.root);
    const full = resolve(base, normalize(key));
    if (full !== base && !full.startsWith(base + sep)) {
      throw new Error('storage key escapes the storage root');
    }
    return full;
  }

  async put(key: string, bytes: Buffer): Promise<StoredObject> {
    const path = this.pathFor(key);
    await mkdir(dirname(path), { recursive: true });
    /* `wx` fails if the key already exists rather than overwriting. A key
       collision is a bug worth hearing about, not a file to silently
       replace — and silently replacing one would be a way to overwrite
       another customer's attachment. */
    await writeFile(path, bytes, { flag: 'wx', mode: 0o600 });
    return { key, byteSize: bytes.byteLength, checksumSha256: sha256(bytes) };
  }

  async get(key: string): Promise<Buffer> {
    return readFile(this.pathFor(key));
  }

  async delete(key: string): Promise<void> {
    await rm(this.pathFor(key), { force: true });
  }

  async exists(key: string): Promise<boolean> {
    try {
      await stat(this.pathFor(key));
      return true;
    } catch {
      return false;
    }
  }
}

/** Keeps bytes in memory. For tests, and for nothing else. */
export class InMemoryStorage implements StorageProvider {
  private readonly objects = new Map<string, Buffer>();

  /* Synchronous bodies returning promises, rather than `async` methods with
     nothing to await — same contract, and the lint rule is right that an
     `async` with no `await` is usually a mistake. */
  put(key: string, bytes: Buffer): Promise<StoredObject> {
    if (this.objects.has(key)) return Promise.reject(new Error('storage key already exists'));
    this.objects.set(key, bytes);
    return Promise.resolve({ key, byteSize: bytes.byteLength, checksumSha256: sha256(bytes) });
  }

  get(key: string): Promise<Buffer> {
    const bytes = this.objects.get(key);
    if (!bytes) return Promise.reject(new Error(`no such object: ${key}`));
    return Promise.resolve(bytes);
  }

  delete(key: string): Promise<void> {
    this.objects.delete(key);
    return Promise.resolve();
  }

  exists(key: string): Promise<boolean> {
    return Promise.resolve(this.objects.has(key));
  }

  get size(): number {
    return this.objects.size;
  }

  /** Tests clear this between cases, exactly as they clear the database. */
  clear(): void {
    this.objects.clear();
  }
}

export function createStorage(root: string): StorageProvider {
  return new LocalFileStorage(join(root, 'attachments'));
}
