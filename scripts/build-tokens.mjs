#!/usr/bin/env node
/**
 * Turns the chosen design direction into CSS custom properties.
 *
 * `docs/design/palettes.json` stays the single source: step 09 built three
 * directions from it and checked every colour pair against WCAG 2.1 AA; this
 * reads the one marked `chosen` and writes the stylesheet the application uses.
 * Nothing here invents a value — if a token is not in that file, it is derived
 * from one that is, and the derivation is visible.
 *
 * Generated rather than hand-written because the alternative is two sources of
 * truth that agree on the day they are written and drift afterwards. The
 * contrast check runs against the JSON; if the CSS were separate, it would be
 * checking a file nobody renders.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const PALETTES = 'docs/design/palettes.json';
const OUT = 'apps/client/src/styles/tokens.css';

/** 8px base → 4 8 16 24 32 48 64 80. Half-step included; it is needed for
    icon gaps and nothing smaller is. */
const SPACE_STEPS = [0.5, 1, 2, 3, 4, 6, 8, 10];

/** A 1.2 modular scale from the direction's body size, rounded to whole
    pixels. Rounding matters: fractional font sizes are rendered
    inconsistently across engines and make vertical rhythm impossible to
    reason about. */
export function typeScale(bodySize) {
  const steps = { xs: -2, sm: -1, base: 0, lg: 1, xl: 2, '2xl': 3, '3xl': 4 };
  return Object.fromEntries(
    Object.entries(steps).map(([name, step]) => [name, Math.round(bodySize * 1.2 ** step)]),
  );
}

export function cssVariables(direction, mode) {
  const palette = direction.modes[mode];
  return Object.entries(palette).map(([name, value]) => [`--color-${kebab(name)}`, value]);
}

function kebab(name) {
  return name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

function block(pairs, indent = '  ') {
  return pairs.map(([name, value]) => `${indent}${name}: ${value};`).join('\n');
}

export function buildTokens(document_) {
  const direction = document_.directions.find((entry) => entry.id === document_.chosen);
  if (!direction) throw new Error(`palettes.json has no direction named ${document_.chosen}`);

  const { scale, fonts } = direction;
  const type = typeScale(scale.bodySize);

  const scalars = [
    ...SPACE_STEPS.map((step) => [
      `--space-${String(step).replace('.', '_')}`,
      `${String(step * scale.base)}px`,
    ]),
    ['--radius', `${String(scale.radius)}px`],
    ['--radius-lg', `${String(scale.radiusLarge)}px`],
    ['--radius-pill', '999px'],
    ...Object.entries(type).map(([name, size]) => [`--text-${name}`, `${String(size)}px`]),
    ['--leading-tight', '1.2'],
    /* 1.6 rather than the Latin-typical 1.5: Arabic sits on a deeper body with
       ascenders and marks above the line, and the research starts its
       evaluation there. One value for both scripts, because two would make
       every mixed paragraph ragged. */
    ['--leading-body', '1.6'],
    ['--weight-regular', '400'],
    ['--weight-strong', String(scale.headingWeight)],
    ['--font-latin', `'${fonts.latin}', Georgia, serif`],
    ['--font-arabic', `'${fonts.arabic}', '${fonts.latin}', serif`],
    ['--font-mono', `'${fonts.mono}', ui-monospace, 'SFMono-Regular', monospace`],
    ['--motion-fast', '160ms'],
    ['--motion-ease', 'cubic-bezier(0.2, 0, 0.2, 1)'],
    ['--focus-width', '2px'],
    ['--focus-offset', '2px'],
  ];

  return `/* Generated by \`npm run build:tokens\` from ${PALETTES}.
   Do not edit by hand — edit the palette and regenerate.
   Direction: ${direction.name} (${direction.id}).
   Every colour pair below is verified by \`npm run check:contrast\`. */

:root {
  color-scheme: light dark;

${block(scalars)}

  /* ${direction.name} — light */
${block(cssVariables(direction, 'light'))}
}

/* Dark is applied three ways, and all three have to agree:
   - \`data-theme="dark"\`        an explicit choice
   - \`prefers-color-scheme\`     the system default, when no choice is stored
   - \`data-theme="light"\`       must survive a dark system setting
   Defining dark only inside the media query is the common bug: the toggle then
   works in one direction and silently fails in the other. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${block(cssVariables(direction, 'dark'), '    ')}
  }
}

:root[data-theme='dark'] {
${block(cssVariables(direction, 'dark'))}
}
`;
}

function main() {
  const document_ = JSON.parse(readFileSync(PALETTES, 'utf8'));
  writeFileSync(OUT, buildTokens(document_));
  console.log(`built ${OUT} from the "${document_.chosen}" direction`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
