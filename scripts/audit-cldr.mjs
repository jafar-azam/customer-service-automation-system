#!/usr/bin/env node
/**
 * Records what this runtime's ICU data actually does for Arabic locales.
 *
 * `docs/research/localization-lebanon.md` marks every `ar-LB` CLDR default as
 * **unverified** and supplies this audit as the way to settle it. The point is
 * not to pick a locale from the output — the product configures calendar,
 * numbering system and time zone explicitly precisely so it does not depend on
 * these defaults. The point is to know what we are overriding, and to notice
 * when a Node upgrade changes it underneath us.
 *
 * Output is committed to `docs/design/cldr-audit.json`. A diff there is a
 * finding, not noise.
 */
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const OUT = 'docs/design/cldr-audit.json';
const LOCALES = ['ar-LB', 'ar', 'ar-SA', 'ar-EG', 'en-LB'];

/** A fixed instant, so the output changes only when the runtime does. */
const INSTANT = new Date('2026-01-15T13:05:00Z');

export function auditLocale(locale) {
  const dates = new Intl.DateTimeFormat(locale, {
    timeZone: 'Asia/Beirut',
    dateStyle: 'full',
    timeStyle: 'short',
  });
  const numbers = new Intl.NumberFormat(locale);
  const resolvedDate = dates.resolvedOptions();

  return {
    locale,
    resolved: {
      locale: resolvedDate.locale,
      calendar: resolvedDate.calendar,
      numberingSystem: resolvedDate.numberingSystem,
      hourCycle: resolvedDate.hourCycle ?? null,
      timeZone: resolvedDate.timeZone,
    },
    numberingSystem: numbers.resolvedOptions().numberingSystem,
    dateExample: dates.format(INSTANT),
    numberExample: numbers.format(1_234_567.89),
    months: Array.from({ length: 12 }, (_, month) =>
      new Intl.DateTimeFormat(locale, {
        calendar: 'gregory',
        timeZone: 'UTC',
        month: 'long',
      }).format(new Date(Date.UTC(2026, month, 15))),
    ),
    pluralCategories: ['zero', 'one', 'two', 'few', 'many', 'other'].filter((category) =>
      new Intl.PluralRules(locale).resolvedOptions().pluralCategories.includes(category),
    ),
  };
}

export function audit() {
  return {
    note: 'Generated by `npm run audit:cldr`. A change here is a runtime change, not an edit.',
    node: process.version,
    icu: process.versions.icu ?? null,
    unicode: process.versions.unicode ?? null,
    instant: INSTANT.toISOString(),
    locales: LOCALES.map(auditLocale),
  };
}

function main() {
  const result = audit();
  writeFileSync(OUT, `${JSON.stringify(result, null, 2)}\n`);
  console.log(`built ${OUT} (Node ${result.node}, ICU ${String(result.icu)})`);
  for (const entry of result.locales) {
    console.log(
      `  ${entry.locale.padEnd(6)} → ${entry.resolved.locale.padEnd(6)} ` +
        `${entry.resolved.calendar}/${entry.numberingSystem} ` +
        `${entry.resolved.hourCycle ?? '-'}  Jan=${entry.months[0] ?? ''}`,
    );
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
